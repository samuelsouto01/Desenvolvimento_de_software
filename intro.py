#  Tipos de dados: inteiros, floats (numeros com virgula, neste caso o ponto), Caracter 'a' ,Strings (cadeia de caracteres "Samuel"), Boolean (Verdadeiro ou falso "True")
#  A linguagem Python não é altamente tipada, ou seja uma variavel (que varia ou não com o decorrer do programa) pode assumir diferentes tipos de dados ao decorrer da execução

